import { start, focus, check, press, summary } from './kb.mjs'
const S = await start('#dropdown'), p = S.p
const btn = p.getByRole('button', { name: 'Actions' }), open = async () => btn.getAttribute('aria-expanded')
await p.locator('nav a').last().focus(); await press(p, 'Tab'); let f = await focus(p)
check('Tab reaches the button', f.startsWith('button "Actions'), f)
await press(p, 'Enter'); f = await focus(p)
check('Enter opens the menu, focus on item 1', (await open()) === 'true' && f === 'menuitem "Rename"', `expanded=${await open()} · ${f}`)
await press(p, 'ArrowDown'); f = await focus(p); check('ArrowDown moves down', f === 'menuitem "Duplicate"', f)
await press(p, 'End'); f = await focus(p); check('End jumps to the last item', f === 'menuitem "Archive"', f)
await press(p, 'ArrowDown'); f = await focus(p); check('ArrowDown at the end wraps to the top', f === 'menuitem "Rename"', f)
await press(p, 'ArrowUp'); f = await focus(p); check('ArrowUp at the top wraps to the bottom', f === 'menuitem "Archive"', f)
await press(p, 'Home', 'ArrowDown', 'Enter'); f = await focus(p)
check('Enter picks the item', (await p.innerText('.page > p')) === 'Picked: duplicate', JSON.stringify(await p.innerText('.page > p')))
check('...closes the menu, returns focus', (await open()) === 'false' && f.startsWith('button "Actions'), `expanded=${await open()} · ${f}`)
await press(p, 'ArrowUp'); f = await focus(p); check('ArrowUp on the button opens at the end', f === 'menuitem "Archive"', f)
await press(p, 'Escape'); f = await focus(p); check('Escape closes, focus back', (await open()) === 'false' && f.startsWith('button "Actions'), `expanded=${await open()} · ${f}`)
await press(p, 'Enter', 'Tab'); check('Tab closes an open menu', (await open()) === 'false', `expanded=${await open()}`)
summary()
await S.close()
