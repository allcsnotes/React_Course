import { JSDOM } from 'jsdom';
const dom = new JSDOM('<div id="root"></div>', { pretendToBeVisual: true });
globalThis.window = dom.window; globalThis.document = dom.window.document;
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const React = await import('react');
const { createRoot } = await import('react-dom/client');
const { Clock } = await import('./clock.mjs');
console.log('-- with StrictMode (development) --');
const r1 = createRoot(document.getElementById('root'));
await React.act(async () => r1.render(<React.StrictMode><Clock /></React.StrictMode>));
console.log('(page closes)');
await React.act(async () => r1.unmount());
console.log('-- without StrictMode --');
document.body.innerHTML = '<div id="root2"></div>';
const r2 = createRoot(document.getElementById('root2'));
await React.act(async () => r2.render(<Clock />));
console.log('(page closes)');
await React.act(async () => r2.unmount());
process.exit(0);
